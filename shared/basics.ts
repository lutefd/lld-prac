const level = (
  title: string,
  description: string,
  requirements: string[],
  input: string,
  output: string,
) => ({ title, description, requirements, examples: [{ input, output }] });
const eq = (expression: string, expected: unknown): Command => ({
  kind: "eq",
  expression,
  expected,
});
const run = (expression: string): Command => ({ kind: "run", expression });
const setup = (expression: string): Command => ({
  kind: "assign",
  name: "s",
  expression,
});

